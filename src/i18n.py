def tr(ui_lang, key, *args):
    """按当前界面语言取文案，支持 % 格式化。未知 key 原样返回。"""
    d = STRINGS.get(ui_lang, STRINGS["zh"])
    s = d.get(key, STRINGS["zh"].get(key, key))
    if args:
        try:
            return s % args
        except Exception:
            return s
    return s
